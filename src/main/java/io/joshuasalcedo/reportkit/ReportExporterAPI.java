package io.joshuasalcedo.reportkit;

import java.io.IOException;
import java.nio.file.Files;
import java.nio.file.Path;
import java.time.Instant;
import java.util.List;
import java.util.Map;
import java.util.function.Consumer;
import io.joshuasalcedo.reportkit.chart.Visualization;
import io.joshuasalcedo.reportkit.report.CompanyProfile;
import io.joshuasalcedo.reportkit.report.DocumentStyle.*;
import io.joshuasalcedo.reportkit.report.Report;
import io.joshuasalcedo.reportkit.report.ReportSection;
import io.joshuasalcedo.reportkit.theme.Theme;

/**
 * Fluent API for building and exporting reports in a single chain.
 *
 * <p>Combines report construction (company profile, header, footer, page config, sections) with
 * export terminals (HTML, PDF, or both). Uses {@link ReportExporter} internally for rendering.
 *
 * <pre>{@code
 * import static io.joshuasalcedo.reportkit.DataKitAPI.*;
 * import static io.joshuasalcedo.reportkit.report.DocumentStyle.*;
 *
 * // Build and export in one fluent chain
 * ReportExporterAPI.report("Daily Shift Report")
 *     .id("shift-001")
 *     .author("Joshua Salcedo")
 *     .description("Shift from 08:00 AM to 08:00 PM")
 *     .company(c -> c
 *         .name("Acme Corp")
 *         .logo("https://cdn.example.com/logo.svg")
 *         .icon("https://cdn.example.com/icon.svg")
 *         .tagline("Innovative Solutions"))
 *     .header(h -> h
 *         .logo("https://cdn.example.com/logo.svg")
 *         .subtitle("Confidential"))
 *     .footer(f -> f
 *         .left("© 2026")
 *         .center("Generated by ReportExporterAPI")
 *         .right("v1.0")
 *         .pageNumbers(true))
 *     .page(p -> p
 *         .size(PageSize.LETTER)
 *         .orientation(Orientation.PORTRAIT)
 *         .margins(20, 20, 20, 20))
 *     .metadata("Department", "Content Management")
 *     .section("Overview", s -> s
 *         .narrative("High-level metrics.")
 *         .add(kpi1, kpi2, kpi3))
 *     .section("Revenue", s -> s.add(donutChart))
 *     .export(Path.of("report"));  // writes report.html + report.pdf
 * }</pre>
 *
 * @author JoshuaSalcedo
 * @see ReportAPI
 * @see ReportExporter
 */
public final class ReportExporterAPI {

  private ReportExporterAPI() {}

  /**
   * Starts building a new exportable report with the given title.
   *
   * @param title report title
   * @return a new {@link ExportableReportBuilder}
   */
  public static ExportableReportBuilder report(String title) {
    return new ExportableReportBuilder(title);
  }

  /**
   * Creates an exportable builder pre-populated from an existing {@link Report}.
   *
   * <p>All fields from the report are mapped into the builder, so you can immediately call an
   * export terminal or override specific values before exporting.
   *
   * <pre>{@code
   * // Export an existing report directly
   * ReportExporterAPI.from(existingReport)
   *     .export(Path.of("output/report"));
   *
   * // Override the style before exporting
   * ReportExporterAPI.from(existingReport)
   *     .style(ReportStyle.MODERN)
   *     .author("New Author")
   *     .export(Path.of("output/report"));
   * }</pre>
   *
   * @param report the pre-built {@link Report} to export
   * @return a new {@link ExportableReportBuilder} with all fields mapped from the report
   */
  public static ExportableReportBuilder from(Report report) {
    var builder =
        new ExportableReportBuilder(report.title())
            .id(report.id())
            .author(report.author())
            .description(report.description())
            .theme(report.theme())
            .createdAt(report.createdAt())
            .metadata(report.metadata());

    // Map sections
    for (ReportSection section : report.sections()) {
      builder.section(section);
    }

    // Map document style components
    if (report.documentStyle() != null) {
      var ds = report.documentStyle();
      if (ds.companyProfile() != null) {
        builder.company(ds.companyProfile());
      }
      if (ds.coverPhoto() != null) {
        builder.coverPhoto(ds.coverPhoto());
      }
      if (ds.header() != null) {
        builder.header(ds.header());
      }
      if (ds.footer() != null) {
        builder.footer(ds.footer());
      }
      if (ds.page() != null) {
        builder.page(ds.page());
      }
    }

    return builder;
  }

  // ── Exportable Report Builder ──────────────────────────────────────────

  /**
   * Fluent builder that extends {@link ReportAPI.ReportBuilder}'s configuration capabilities with
   * export terminal operations.
   *
   * <p>All builder methods return {@code this} for chaining. Terminal methods ({@link #toHTML()},
   * {@link #toPDF()}, {@link #export(Path)}) trigger rendering.
   */
  public static final class ExportableReportBuilder {

    private final ReportAPI.ReportBuilder delegate;
    private ReportExporter exporter;
    private ReportStyle reportStyle = ReportStyle.DEFAULT;

    private ExportableReportBuilder(String title) {
      this.delegate = ReportAPI.report(title);
    }

    // ── Core fields ────────────────────────────────────────────────

    /** Sets the unique report identifier. Defaults to a random UUID. */
    public ExportableReportBuilder id(String id) {
      delegate.id(id);
      return this;
    }

    /** Sets the report author. */
    public ExportableReportBuilder author(String author) {
      delegate.author(author);
      return this;
    }

    /** Sets the executive summary or subtitle. */
    public ExportableReportBuilder description(String description) {
      delegate.description(description);
      return this;
    }

    /** Sets the visual theme. Defaults to {@link Theme#LIGHT}. */
    public ExportableReportBuilder theme(Theme theme) {
      delegate.theme(theme);
      return this;
    }

    /** Sets the creation timestamp. Defaults to {@link Instant#now()}. */
    public ExportableReportBuilder createdAt(Instant createdAt) {
      delegate.createdAt(createdAt);
      return this;
    }

    /** Adds a key-value metadata entry. Can be called multiple times. */
    public ExportableReportBuilder metadata(String key, String value) {
      delegate.metadata(key, value);
      return this;
    }

    /** Adds all entries from the given metadata map. */
    public ExportableReportBuilder metadata(Map<String, String> metadata) {
      delegate.metadata(metadata);
      return this;
    }

    // ── Company Profile ────────────────────────────────────────────

    /**
     * Configures the company profile using a builder lambda.
     *
     * <pre>{@code
     * .company(c -> c
     *     .name("Acme Corp")
     *     .logo("https://example.com/logo.svg")
     *     .tagline("Innovative Solutions")
     *     .contact("info@acme.com", "+1-555-0100", "https://acme.com"))
     * }</pre>
     */
    public ExportableReportBuilder company(Consumer<ReportAPI.CompanyProfileBuilder> config) {
      delegate.company(config);
      return this;
    }

    /** Sets the company profile with just a name and logo URL. */
    public ExportableReportBuilder company(String name, String logoUrl) {
      delegate.company(name, logoUrl);
      return this;
    }

    /** Sets the company profile directly. */
    public ExportableReportBuilder company(CompanyProfile profile) {
      delegate.company(profile);
      return this;
    }

    // ── Cover Photo ────────────────────────────────────────────────

    /** Sets the cover photo with a caption. */
    public ExportableReportBuilder coverPhoto(String imageUrl, String caption) {
      delegate.coverPhoto(imageUrl, caption);
      return this;
    }

    /** Sets the cover photo with no caption. */
    public ExportableReportBuilder coverPhoto(String imageUrl) {
      delegate.coverPhoto(imageUrl);
      return this;
    }

    /** Sets the cover photo directly. */
    public ExportableReportBuilder coverPhoto(CoverPhoto coverPhoto) {
      delegate.coverPhoto(coverPhoto);
      return this;
    }

    // ── Header ─────────────────────────────────────────────────────

    /**
     * Configures the page header using a builder lambda.
     *
     * <pre>{@code
     * .header(h -> h
     *     .logo("https://example.com/logo.svg")
     *     .companyName("Acme Corp")
     *     .subtitle("Confidential"))
     * }</pre>
     */
    public ExportableReportBuilder header(Consumer<ReportAPI.HeaderBuilder> config) {
      delegate.header(config);
      return this;
    }

    /** Sets the header with logo, company name, and subtitle. */
    public ExportableReportBuilder header(String logoUrl, String companyName, String subtitle) {
      delegate.header(logoUrl, companyName, subtitle);
      return this;
    }

    /** Sets the header with just a logo URL. */
    public ExportableReportBuilder header(String logoUrl) {
      delegate.header(logoUrl);
      return this;
    }

    /** Sets the header directly. */
    public ExportableReportBuilder header(Header header) {
      delegate.header(header);
      return this;
    }

    // ── Footer ─────────────────────────────────────────────────────

    /**
     * Configures the page footer using a builder lambda.
     *
     * <pre>{@code
     * .footer(f -> f
     *     .left("© 2026")
     *     .center("Generated by ReportExporterAPI")
     *     .right("v1.0")
     *     .pageNumbers(true))
     * }</pre>
     */
    public ExportableReportBuilder footer(Consumer<ReportAPI.FooterBuilder> config) {
      delegate.footer(config);
      return this;
    }

    /** Sets the footer with three text zones and page number control. */
    public ExportableReportBuilder footer(
        String left, String center, String right, boolean showPageNumbers) {
      delegate.footer(left, center, right, showPageNumbers);
      return this;
    }

    /** Sets the footer with just center text and page numbers enabled. */
    public ExportableReportBuilder footer(String centerText) {
      delegate.footer(centerText);
      return this;
    }

    /** Sets the footer directly. */
    public ExportableReportBuilder footer(Footer footer) {
      delegate.footer(footer);
      return this;
    }

    // ── Page Config ────────────────────────────────────────────────

    /**
     * Configures the page layout using a builder lambda.
     *
     * <pre>{@code
     * .page(p -> p
     *     .size(PageSize.LETTER)
     *     .orientation(Orientation.PORTRAIT)
     *     .margins(20, 20, 20, 20))
     * }</pre>
     */
    public ExportableReportBuilder page(Consumer<ReportAPI.PageBuilder> config) {
      delegate.page(config);
      return this;
    }

    /** Sets the page size and orientation with default margins. */
    public ExportableReportBuilder page(PageSize size, Orientation orientation) {
      delegate.page(size, orientation);
      return this;
    }

    /** Sets the page config directly. */
    public ExportableReportBuilder page(PageConfig pageConfig) {
      delegate.page(pageConfig);
      return this;
    }

    // ── Sections ───────────────────────────────────────────────────

    /**
     * Adds a section using a builder lambda.
     *
     * <pre>{@code
     * .section("Overview", s -> s
     *     .narrative("High-level metrics.")
     *     .add(kpi1, kpi2, kpi3))
     * }</pre>
     */
    public ExportableReportBuilder section(
        String heading, Consumer<ReportAPI.SectionBuilder> config) {
      delegate.section(heading, config);
      return this;
    }

    /** Adds a section with a heading and visualizations. */
    public ExportableReportBuilder section(String heading, List<Visualization> visualizations) {
      delegate.section(heading, visualizations);
      return this;
    }

    /** Adds a section with heading, narrative, and visualizations. */
    public ExportableReportBuilder section(
        String heading, String narrative, List<Visualization> visualizations) {
      delegate.section(heading, narrative, visualizations);
      return this;
    }

    /** Adds a pre-built section. */
    public ExportableReportBuilder section(ReportSection section) {
      delegate.section(section);
      return this;
    }

    // ── Report Style ───────────────────────────────────────────────

    /**
     * Sets the visual style for the rendered output.
     *
     * <pre>{@code
     * .style(ReportStyle.COMPACT)
     * .style(ReportStyle.MODERN)
     * .style(ReportStyle.CORPORATE)
     * }</pre>
     *
     * @param style a {@link ReportStyle} preset or custom style
     */
    public ExportableReportBuilder style(ReportStyle style) {
      this.reportStyle = style;
      return this;
    }

    /**
     * Customizes the visual style using the builder.
     *
     * <pre>{@code
     * .style(s -> s
     *     .fontFamily("Inter, sans-serif")
     *     .primaryColor("#2563eb")
     *     .coverLogoHeight(80)
     *     .borderRadius(12)
     *     .kpiValueFontSize("24pt"))
     * }</pre>
     *
     * @param config consumer that configures the style builder
     */
    public ExportableReportBuilder style(Consumer<ReportStyle.Builder> config) {
      var b = ReportStyle.builder();
      config.accept(b);
      this.reportStyle = b.build();
      return this;
    }

    /**
     * Customizes the visual style by modifying a preset.
     *
     * <pre>{@code
     * .style(ReportStyle.MODERN, s -> s
     *     .primaryColor("#dc2626")
     *     .headingColor("#991b1b"))
     * }</pre>
     *
     * @param base base preset to start from
     * @param config consumer that overrides specific values
     */
    public ExportableReportBuilder style(ReportStyle base, Consumer<ReportStyle.Builder> config) {
      var b = base.toBuilder();
      config.accept(b);
      this.reportStyle = b.build();
      return this;
    }

    // ── Custom exporter ────────────────────────────────────────────

    /**
     * Sets a custom {@link ReportExporter} to use for export. If not called, a default exporter is
     * created.
     */
    public ExportableReportBuilder exporter(ReportExporter exporter) {
      this.exporter = exporter;
      return this;
    }

    // ── Build (no export) ──────────────────────────────────────────

    /**
     * Builds the {@link Report} without exporting.
     *
     * @return the immutable {@link Report} record
     */
    public Report build() {
      return delegate.build();
    }

    // ── Export terminals ───────────────────────────────────────────

    /**
     * Builds the report and renders it to HTML.
     *
     * @return the rendered {@link Html}
     */
    public Html toHTML() {
      return getExporter().toHTML(delegate.build(), reportStyle);
    }

    /**
     * Builds the report, renders it to HTML, and writes to the given path.
     *
     * @param path file path to write (e.g. {@code Path.of("report.html")})
     * @return the rendered {@link Html}
     * @throws ReportExportException if writing fails
     */
    public Html toHTML(Path path) {
      Html html = toHTML();
      writeString(path, html.html());
      return html;
    }

    /**
     * Builds the report and renders it to PDF.
     *
     * @return the rendered {@link PDF}
     */
    public PDF toPDF() {
      return getExporter().reportToPDF(delegate.build(), reportStyle);
    }

    /**
     * Builds the report, renders it to PDF, and writes to the given path.
     *
     * @param path file path to write (e.g. {@code Path.of("report.pdf")})
     * @return the rendered {@link PDF}
     * @throws ReportExportException if writing fails
     */
    public PDF toPDF(Path path) {
      PDF pdf = toPDF();
      writeBytes(path, pdf.bytes());
      return pdf;
    }

    /**
     * Builds the report and exports both HTML and PDF using the given base name.
     *
     * <p>Creates two files: {@code <basePath>.html} and {@code <basePath>.pdf}.
     *
     * <pre>{@code
     * ExportResult result = ReportExporterAPI.report("My Report")
     *     .author("Josh")
     *     .section("Data", List.of(table))
     *     .export(Path.of("output/my-report"));
     * // Creates: output/my-report.html and output/my-report.pdf
     * }</pre>
     *
     * @param basePath base file path without extension
     * @return an {@link ExportResult} with both outputs and file paths
     * @throws ReportExportException if rendering or writing fails
     */
    public ExportResult export(Path basePath) {
      Report report = delegate.build();
      ReportExporter exp = getExporter();

      Html html = exp.toHTML(report, reportStyle);
      Path htmlPath = Path.of(basePath + ".html");
      writeString(htmlPath, html.html());

      PDF pdf = exp.toPDF(html);
      Path pdfPath = Path.of(basePath + ".pdf");
      writeBytes(pdfPath, pdf.bytes());

      return new ExportResult(report, html, htmlPath, pdf, pdfPath);
    }

    private ReportExporter getExporter() {
      if (exporter == null) {
        exporter = ReportExporter.createDefault();
      }
      return exporter;
    }

    private static void writeString(Path path, String content) {
      try {
        if (path.getParent() != null) {
          Files.createDirectories(path.getParent());
        }
        Files.writeString(path, content);
      } catch (IOException e) {
        throw new ReportExportException("Failed to write file: " + path, e);
      }
    }

    private static void writeBytes(Path path, byte[] bytes) {
      try {
        if (path.getParent() != null) {
          Files.createDirectories(path.getParent());
        }
        Files.write(path, bytes);
      } catch (IOException e) {
        throw new ReportExportException("Failed to write file: " + path, e);
      }
    }
  }

  // ── Export Result ───────────────────────────────────────────────────────

  /**
   * Result of exporting a report to both HTML and PDF.
   *
   * @param report the built report
   * @param html rendered HTML content
   * @param htmlPath path where HTML was written
   * @param pdf rendered PDF content
   * @param pdfPath path where PDF was written
   */
  public record ExportResult(Report report, Html html, Path htmlPath, PDF pdf, Path pdfPath) {}
}
