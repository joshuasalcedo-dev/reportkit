package io.joshuasalcedo.reportkit;

import java.time.Instant;
import java.util.*;
import java.util.function.Consumer;
import io.joshuasalcedo.reportkit.chart.Visualization;
import io.joshuasalcedo.reportkit.report.CompanyProfile;
import io.joshuasalcedo.reportkit.report.DocumentStyle;
import io.joshuasalcedo.reportkit.report.DocumentStyle.*;
import io.joshuasalcedo.reportkit.report.Report;
import io.joshuasalcedo.reportkit.report.ReportSection;
import io.joshuasalcedo.reportkit.theme.Theme;

/**
 * Fluent builder API for constructing reports.
 *
 * <p>Entry point for building a {@link Report} with chained method calls. Each style component
 * (company profile, header, footer, page config) has its own nested builder, configurable via
 * lambda.
 *
 * <pre>{@code
 * import static io.joshuasalcedo.reportkit.DataKitAPI.*;
 *
 * Report report = ReportAPI.report("Daily Shift Report")
 *     .id("shift-001")
 *     .author("Joshua Salcedo")
 *     .description("Shift from 08:00 AM to 08:00 PM")
 *     .company(c -> c
 *         .name("Acme Corp")
 *         .logo("https://cdn.example.com/logo.svg")
 *         .icon("https://cdn.example.com/icon.svg")
 *         .tagline("Innovative Solutions"))
 *     .header(h -> h
 *         .logo("https://cdn.example.com/logo.svg")
 *         .companyName("Acme Corp")
 *         .subtitle("Confidential"))
 *     .footer(f -> f
 *         .left("Acme Corp © 2026")
 *         .center("Generated by ReportKit")
 *         .right("ReportAPI v1.0")
 *         .pageNumbers(true))
 *     .page(p -> p
 *         .size(PageSize.LETTER)
 *         .orientation(Orientation.PORTRAIT)
 *         .margins(20, 20, 20, 20))
 *     .metadata("Department", "Content Management")
 *     .metadata("Version", "1.0")
 *     .theme(Theme.LIGHT)
 *     .section("Shift Overview", s -> s
 *         .narrative("High-level financial and time metrics.")
 *         .add(kpi1, kpi2, kpi3))
 *     .section("Revenue Breakdown", s -> s
 *         .narrative("Distribution of gross revenue.")
 *         .add(donutChart))
 *     .build();
 * }</pre>
 *
 * <p>Shorthand overloads are available for simple cases:
 *
 * <pre>{@code
 * ReportAPI.report("Simple Report")
 *     .author("HR Department")
 *     .header("logo.svg", "Acme Corp", "Confidential")
 *     .footer("© 2026", "Generated by ReportKit", "v1.0", true)
 *     .section("Data", List.of(dataTable))
 *     .build();
 * }</pre>
 *
 * @author JoshuaSalcedo
 * @see DataKitAPI
 * @see Report
 */
public final class ReportAPI {

  private ReportAPI() {}

  /**
   * Starts building a new report with the given title.
   *
   * @param title report title
   * @return a new {@link ReportBuilder}
   */
  public static ReportBuilder report(String title) {
    return new ReportBuilder(title);
  }

  // ── Report Builder ─────────────────────────────────────────────────────

  /**
   * Fluent builder for {@link Report}.
   *
   * <p>Call {@link #build()} to produce the final immutable {@link Report} record. A {@link
   * DocumentStyle} is automatically assembled from the configured company profile, cover photo,
   * header, footer, and page settings.
   */
  public static final class ReportBuilder {

    private String id;
    private final String title;
    private String author = "";
    private String description = "";
    private final List<ReportSection> sections = new ArrayList<>();
    private Theme theme = Theme.LIGHT;
    private final Map<String, String> metadata = new LinkedHashMap<>();
    private Instant createdAt = Instant.now();

    // Style components
    private CompanyProfile companyProfile;
    private CoverPhoto coverPhoto;
    private Header header;
    private Footer footer;
    private PageConfig pageConfig;

    private ReportBuilder(String title) {
      this.title = Objects.requireNonNull(title, "title");
      this.id = UUID.randomUUID().toString();
    }

    /** Sets the unique report identifier. Defaults to a random UUID. */
    public ReportBuilder id(String id) {
      this.id = id;
      return this;
    }

    /** Sets the report author. */
    public ReportBuilder author(String author) {
      this.author = author;
      return this;
    }

    /** Sets the executive summary or subtitle. */
    public ReportBuilder description(String description) {
      this.description = description;
      return this;
    }

    /** Sets the visual theme. Defaults to {@link Theme#LIGHT}. */
    public ReportBuilder theme(Theme theme) {
      this.theme = theme;
      return this;
    }

    /** Sets the creation timestamp. Defaults to {@link Instant#now()}. */
    public ReportBuilder createdAt(Instant createdAt) {
      this.createdAt = createdAt;
      return this;
    }

    /** Adds a key-value metadata entry. Can be called multiple times. */
    public ReportBuilder metadata(String key, String value) {
      this.metadata.put(key, value);
      return this;
    }

    /** Adds all entries from the given metadata map. */
    public ReportBuilder metadata(Map<String, String> metadata) {
      this.metadata.putAll(metadata);
      return this;
    }

    // ── Company Profile ────────────────────────────────────────────

    /**
     * Configures the company profile using a builder lambda.
     *
     * <pre>{@code
     * .company(c -> c
     *     .name("Acme Corp")
     *     .logo("https://example.com/logo.svg")
     *     .icon("https://example.com/icon.svg")
     *     .tagline("Innovative Solutions")
     *     .registration("SEC File No. 001-12345")
     *     .address("123 Main Street, New York, NY")
     *     .contact("info@acme.com", "+1-555-0100", "https://acme.com"))
     * }</pre>
     */
    public ReportBuilder company(Consumer<CompanyProfileBuilder> config) {
      var b = new CompanyProfileBuilder();
      config.accept(b);
      this.companyProfile = b.build();
      return this;
    }

    /** Sets the company profile with just a name and logo URL. */
    public ReportBuilder company(String name, String logoUrl) {
      this.companyProfile = new CompanyProfile(name, logoUrl);
      return this;
    }

    /** Sets the company profile directly. */
    public ReportBuilder company(CompanyProfile profile) {
      this.companyProfile = profile;
      return this;
    }

    // ── Cover Photo ────────────────────────────────────────────────

    /** Sets the cover photo with a caption. */
    public ReportBuilder coverPhoto(String imageUrl, String caption) {
      this.coverPhoto = new CoverPhoto(imageUrl, caption);
      return this;
    }

    /** Sets the cover photo with no caption. */
    public ReportBuilder coverPhoto(String imageUrl) {
      this.coverPhoto = new CoverPhoto(imageUrl);
      return this;
    }

    /** Sets the cover photo directly. */
    public ReportBuilder coverPhoto(CoverPhoto coverPhoto) {
      this.coverPhoto = coverPhoto;
      return this;
    }

    // ── Header ─────────────────────────────────────────────────────

    /**
     * Configures the page header using a builder lambda.
     *
     * <pre>{@code
     * .header(h -> h
     *     .logo("https://example.com/logo.svg")
     *     .companyName("Acme Corp")
     *     .subtitle("Confidential"))
     * }</pre>
     */
    public ReportBuilder header(Consumer<HeaderBuilder> config) {
      var b = new HeaderBuilder();
      config.accept(b);
      this.header = b.build();
      return this;
    }

    /** Sets the header with logo, company name, and subtitle. */
    public ReportBuilder header(String logoUrl, String companyName, String subtitle) {
      this.header = new Header(logoUrl, companyName, subtitle);
      return this;
    }

    /** Sets the header with just a logo URL. */
    public ReportBuilder header(String logoUrl) {
      this.header = new Header(logoUrl);
      return this;
    }

    /** Sets the header directly. */
    public ReportBuilder header(Header header) {
      this.header = header;
      return this;
    }

    // ── Footer ─────────────────────────────────────────────────────

    /**
     * Configures the page footer using a builder lambda.
     *
     * <pre>{@code
     * .footer(f -> f
     *     .left("Acme Corp © 2026")
     *     .center("Generated by ReportKit")
     *     .right("ReportAPI v1.0")
     *     .pageNumbers(true))
     * }</pre>
     */
    public ReportBuilder footer(Consumer<FooterBuilder> config) {
      var b = new FooterBuilder();
      config.accept(b);
      this.footer = b.build();
      return this;
    }

    /** Sets the footer with three text zones and page number control. */
    public ReportBuilder footer(String left, String center, String right, boolean showPageNumbers) {
      this.footer = new Footer(left, center, right, showPageNumbers);
      return this;
    }

    /** Sets the footer with just center text and page numbers enabled. */
    public ReportBuilder footer(String centerText) {
      this.footer = new Footer(centerText);
      return this;
    }

    /** Sets the footer directly. */
    public ReportBuilder footer(Footer footer) {
      this.footer = footer;
      return this;
    }

    // ── Page Config ────────────────────────────────────────────────

    /**
     * Configures the page layout using a builder lambda.
     *
     * <pre>{@code
     * .page(p -> p
     *     .size(PageSize.LETTER)
     *     .orientation(Orientation.PORTRAIT)
     *     .margins(20, 20, 20, 20))
     * }</pre>
     */
    public ReportBuilder page(Consumer<PageBuilder> config) {
      var b = new PageBuilder();
      config.accept(b);
      this.pageConfig = b.build();
      return this;
    }

    /** Sets the page size and orientation with default margins. */
    public ReportBuilder page(PageSize size, Orientation orientation) {
      this.pageConfig = new PageConfig(size, orientation);
      return this;
    }

    /** Sets the page config directly. */
    public ReportBuilder page(PageConfig pageConfig) {
      this.pageConfig = pageConfig;
      return this;
    }

    // ── Sections ───────────────────────────────────────────────────

    /**
     * Adds a section using a builder lambda.
     *
     * <pre>{@code
     * .section("Overview", s -> s
     *     .narrative("High-level metrics for this shift.")
     *     .add(kpi1, kpi2, kpi3))
     * }</pre>
     */
    public ReportBuilder section(String heading, Consumer<SectionBuilder> config) {
      var b = new SectionBuilder(heading);
      config.accept(b);
      this.sections.add(b.build());
      return this;
    }

    /** Adds a section with a heading and visualizations. */
    public ReportBuilder section(String heading, List<Visualization> visualizations) {
      this.sections.add(new ReportSection(heading, visualizations));
      return this;
    }

    /** Adds a section with a heading, narrative, and visualizations. */
    public ReportBuilder section(
        String heading, String narrative, List<Visualization> visualizations) {
      this.sections.add(new ReportSection(heading, narrative, visualizations));
      return this;
    }

    /** Adds a pre-built section. */
    public ReportBuilder section(ReportSection section) {
      this.sections.add(section);
      return this;
    }

    // ── Build ──────────────────────────────────────────────────────

    /**
     * Builds the final immutable {@link Report}.
     *
     * <p>If any style component (company, cover photo, header, footer, page) was configured, a
     * {@link DocumentStyle} is automatically assembled.
     *
     * @return a new {@link Report} record
     */
    public Report build() {
      DocumentStyle style = null;
      if (companyProfile != null
          || coverPhoto != null
          || header != null
          || footer != null
          || pageConfig != null) {
        style = new DocumentStyle(companyProfile, coverPhoto, header, footer, pageConfig);
      }
      return new Report(
          id,
          title,
          author,
          description,
          List.copyOf(sections),
          theme,
          Map.copyOf(metadata),
          createdAt,
          style);
    }
  }

  // ── Company Profile Builder ────────────────────────────────────────────

  /**
   * Fluent builder for {@link CompanyProfile}.
   *
   * <p>Used inside {@link ReportBuilder#company(Consumer)} to configure company branding,
   * registration, and contact details.
   */
  public static final class CompanyProfileBuilder {

    private String name;
    private String logoUrl;
    private String iconUrl;
    private String tagline;
    private String registrationInfo;
    private String address;
    private String email;
    private String phone;
    private String website;

    /** Sets the legal entity name. */
    public CompanyProfileBuilder name(String name) {
      this.name = name;
      return this;
    }

    /** Sets the full logo URL for the cover page (recommended: 200x60px). */
    public CompanyProfileBuilder logo(String logoUrl) {
      this.logoUrl = logoUrl;
      return this;
    }

    /** Sets the small icon URL for running page headers (recommended: 24x24px). */
    public CompanyProfileBuilder icon(String iconUrl) {
      this.iconUrl = iconUrl;
      return this;
    }

    /** Sets the company tagline or slogan. */
    public CompanyProfileBuilder tagline(String tagline) {
      this.tagline = tagline;
      return this;
    }

    /** Sets the regulatory registration info (e.g. SEC file number, ABN). */
    public CompanyProfileBuilder registration(String info) {
      this.registrationInfo = info;
      return this;
    }

    /** Sets the registered office address. */
    public CompanyProfileBuilder address(String address) {
      this.address = address;
      return this;
    }

    /** Sets the contact email. */
    public CompanyProfileBuilder email(String email) {
      this.email = email;
      return this;
    }

    /** Sets the contact phone. */
    public CompanyProfileBuilder phone(String phone) {
      this.phone = phone;
      return this;
    }

    /** Sets the company website URL. */
    public CompanyProfileBuilder website(String website) {
      this.website = website;
      return this;
    }

    /** Sets email, phone, and website in one call. */
    public CompanyProfileBuilder contact(String email, String phone, String website) {
      this.email = email;
      this.phone = phone;
      this.website = website;
      return this;
    }

    CompanyProfile build() {
      return new CompanyProfile(
          name, logoUrl, iconUrl, tagline, registrationInfo, address, email, phone, website);
    }
  }

  // ── Header Builder ─────────────────────────────────────────────────────

  /**
   * Fluent builder for {@link Header}.
   *
   * <p>Used inside {@link ReportBuilder#header(Consumer)} to configure the running page header with
   * logo, company name, and subtitle.
   */
  public static final class HeaderBuilder {

    private String logoUrl;
    private String companyName;
    private String subtitle;

    /** Sets the logo/icon URL for the header. */
    public HeaderBuilder logo(String logoUrl) {
      this.logoUrl = logoUrl;
      return this;
    }

    /** Sets the company name displayed in the header. */
    public HeaderBuilder companyName(String companyName) {
      this.companyName = companyName;
      return this;
    }

    /** Sets the subtitle/classification label (e.g. "Confidential"). */
    public HeaderBuilder subtitle(String subtitle) {
      this.subtitle = subtitle;
      return this;
    }

    Header build() {
      return new Header(logoUrl, companyName, subtitle);
    }
  }

  // ── Footer Builder ─────────────────────────────────────────────────────

  /**
   * Fluent builder for {@link Footer}.
   *
   * <p>Used inside {@link ReportBuilder#footer(Consumer)} to configure the three footer text zones
   * and page numbering.
   */
  public static final class FooterBuilder {

    private String left;
    private String center;
    private String right;
    private boolean showPageNumbers = true;

    /** Sets the left footer text. */
    public FooterBuilder left(String text) {
      this.left = text;
      return this;
    }

    /** Sets the center footer text. */
    public FooterBuilder center(String text) {
      this.center = text;
      return this;
    }

    /** Sets the right footer text. */
    public FooterBuilder right(String text) {
      this.right = text;
      return this;
    }

    /** Controls whether page numbers are shown. Defaults to {@code true}. */
    public FooterBuilder pageNumbers(boolean show) {
      this.showPageNumbers = show;
      return this;
    }

    Footer build() {
      return new Footer(left, center, right, showPageNumbers);
    }
  }

  // ── Page Builder ───────────────────────────────────────────────────────

  /**
   * Fluent builder for {@link PageConfig}.
   *
   * <p>Used inside {@link ReportBuilder#page(Consumer)} to configure paper size, orientation, and
   * margins.
   */
  public static final class PageBuilder {

    private PageSize size = PageSize.LETTER;
    private Orientation orientation = Orientation.PORTRAIT;
    private Margins margins = Margins.DEFAULT;

    /** Sets the paper size. Defaults to {@link PageSize#LETTER}. */
    public PageBuilder size(PageSize size) {
      this.size = size;
      return this;
    }

    /** Sets the page orientation. Defaults to {@link Orientation#PORTRAIT}. */
    public PageBuilder orientation(Orientation orientation) {
      this.orientation = orientation;
      return this;
    }

    /** Sets individual margins in millimeters. */
    public PageBuilder margins(double top, double right, double bottom, double left) {
      this.margins = new Margins(top, right, bottom, left);
      return this;
    }

    /** Sets uniform margins on all sides in millimeters. */
    public PageBuilder margins(double allMm) {
      this.margins = new Margins(allMm);
      return this;
    }

    /** Sets the margins directly. */
    public PageBuilder margins(Margins margins) {
      this.margins = margins;
      return this;
    }

    /** Shortcut: A4 portrait with default margins. */
    public PageBuilder a4() {
      this.size = PageSize.A4;
      this.orientation = Orientation.PORTRAIT;
      return this;
    }

    /** Shortcut: Letter portrait with default margins. */
    public PageBuilder letter() {
      this.size = PageSize.LETTER;
      this.orientation = Orientation.PORTRAIT;
      return this;
    }

    /** Shortcut: sets orientation to landscape. */
    public PageBuilder landscape() {
      this.orientation = Orientation.LANDSCAPE;
      return this;
    }

    PageConfig build() {
      return new PageConfig(size, orientation, margins);
    }
  }

  // ── Section Builder ────────────────────────────────────────────────────

  /**
   * Fluent builder for {@link ReportSection}.
   *
   * <p>Used inside {@link ReportBuilder#section(String, Consumer)} to configure section narrative
   * and visualizations.
   *
   * <pre>{@code
   * .section("Overview", s -> s
   *     .narrative("High-level metrics for this shift.")
   *     .add(kpi1, kpi2, kpi3)
   *     .add(donutChart))
   * }</pre>
   */
  public static final class SectionBuilder {

    private final String heading;
    private String narrative = "";
    private final List<Visualization> visualizations = new ArrayList<>();

    private SectionBuilder(String heading) {
      this.heading = Objects.requireNonNull(heading, "heading");
    }

    /** Sets the section narrative/commentary. */
    public SectionBuilder narrative(String narrative) {
      this.narrative = narrative;
      return this;
    }

    /** Adds one or more visualizations to this section. */
    public SectionBuilder add(Visualization... visualizations) {
      Collections.addAll(this.visualizations, visualizations);
      return this;
    }

    /** Adds a list of visualizations to this section. */
    public SectionBuilder add(List<Visualization> visualizations) {
      this.visualizations.addAll(visualizations);
      return this;
    }

    ReportSection build() {
      return new ReportSection(heading, narrative, List.copyOf(visualizations));
    }
  }
}
