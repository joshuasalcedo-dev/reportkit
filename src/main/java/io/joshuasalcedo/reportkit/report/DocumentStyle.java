package io.joshuasalcedo.reportkit.report;

/**
 * Rendering configuration for PDF/HTML export: header branding, footer layout, page geometry, cover
 * photo, and company profile.
 *
 * <p>Attach to a {@link Report} to control how it appears when exported. All sub-records are nested
 * here for a clean import experience.
 *
 * <pre>{@code
 * import static io.joshuasalcedo.reportkit.DataKitAPI.*;
 *
 * var profile = companyProfile("Acme Corp", "https://example.com/logo.svg")
 *     .withIcon("https://example.com/icon.svg")
 *     .withTagline("Innovative Solutions")
 *     .withAddress("123 Main St, New York, NY 10001");
 *
 * var style = documentStyle(
 *     profile,
 *     coverPhoto("https://example.com/hero.jpg", "Q1 2026 Financial Overview"),
 *     header("Confidential"),
 *     footer("Acme Corp © 2026", null, "Generated by ReportAPI", true),
 *     pageConfig(PageSize.LETTER, Orientation.PORTRAIT)
 * );
 * }</pre>
 *
 * @param companyProfile company branding and identification (nullable)
 * @param coverPhoto hero image displayed on the report cover page (nullable)
 * @param header branding shown at the top of each page (nullable for no header)
 * @param footer text shown at the bottom of each page (nullable for no footer)
 * @param page page size, orientation, and margins
 */
public record DocumentStyle(
    CompanyProfile companyProfile,
    CoverPhoto coverPhoto,
    Header header,
    Footer footer,
    PageConfig page) {

  /** Creates a document style without company profile or cover photo (backward compatible). */
  public DocumentStyle(Header header, Footer footer, PageConfig page) {
    this(null, null, header, footer, page);
  }

  /** Creates a document style with only a header, using default footer and page config. */
  public DocumentStyle(Header header) {
    this(null, null, header, Footer.DEFAULT, PageConfig.DEFAULT);
  }

  /** Creates a document style with header and footer, using default page config. */
  public DocumentStyle(Header header, Footer footer) {
    this(null, null, header, footer, PageConfig.DEFAULT);
  }

  /** Creates a full document style with company profile and cover photo. */
  public DocumentStyle(
      CompanyProfile companyProfile, CoverPhoto coverPhoto, Header header, Footer footer) {
    this(companyProfile, coverPhoto, header, footer, PageConfig.DEFAULT);
  }

  /**
   * Cover photo displayed on the report cover page.
   *
   * <p>Standard size: full page width, max height 180px.
   *
   * @param imageUrl path or URL to the cover image (PNG/JPG recommended)
   * @param caption optional caption or alt text (nullable)
   */
  public record CoverPhoto(String imageUrl, String caption) {

    /** Creates a cover photo with no caption. */
    public CoverPhoto(String imageUrl) {
      this(imageUrl, null);
    }
  }

  /**
   * Page header shown at the top of every page.
   *
   * <p>When a {@link CompanyProfile} is set on the document style, the header icon and company name
   * are sourced from the profile. The {@code subtitle} field here controls
   * classification/confidentiality labels.
   *
   * @param logoUrl path or URL to a logo image (nullable — prefer CompanyProfile.iconUrl)
   * @param companyName organization name displayed in the header (nullable — prefer
   *     CompanyProfile.name)
   * @param subtitle tagline, classification, or subtitle (nullable)
   */
  public record Header(String logoUrl, String companyName, String subtitle) {

    /** Creates a header with just a logo. */
    public Header(String logoUrl) {
      this(logoUrl, null, null);
    }

    /** Creates a header with a logo and company name. */
    public Header(String logoUrl, String companyName) {
      this(logoUrl, companyName, null);
    }

    /** Creates a header with only a subtitle/classification (icon from CompanyProfile). */
    public static Header withSubtitle(String subtitle) {
      return new Header(null, null, subtitle);
    }
  }

  /**
   * Page footer with three text zones (left/center/right) and optional page numbering.
   *
   * @param leftText text on the left side (nullable)
   * @param centerText text in the center (nullable)
   * @param rightText text on the right side (nullable)
   * @param showPageNumbers {@code true} to render "Page X of Y"
   */
  public record Footer(
      String leftText, String centerText, String rightText, boolean showPageNumbers) {

    /** Default footer: no text, page numbers enabled. */
    public static final Footer DEFAULT = new Footer(null, null, null, true);

    /** Creates a footer with center text and page numbers. */
    public Footer(String centerText) {
      this(null, centerText, null, true);
    }
  }

  /**
   * Physical page configuration.
   *
   * @param size paper size
   * @param orientation portrait or landscape
   * @param margins page margins
   */
  public record PageConfig(PageSize size, Orientation orientation, Margins margins) {

    /** Default: Letter, portrait, 1-inch margins. */
    public static final PageConfig DEFAULT =
        new PageConfig(PageSize.LETTER, Orientation.PORTRAIT, Margins.DEFAULT);

    /** Creates a page config with default 1-inch margins. */
    public PageConfig(PageSize size, Orientation orientation) {
      this(size, orientation, Margins.DEFAULT);
    }
  }

  /**
   * Page margins in millimeters.
   *
   * @param topMm top margin
   * @param rightMm right margin
   * @param bottomMm bottom margin
   * @param leftMm left margin
   */
  public record Margins(double topMm, double rightMm, double bottomMm, double leftMm) {

    /** 1-inch (25.4 mm) margins on all sides. */
    public static final Margins DEFAULT = new Margins(25.4, 25.4, 25.4, 25.4);

    /** 0.5-inch (12.7 mm) margins on all sides. */
    public static final Margins NARROW = new Margins(12.7, 12.7, 12.7, 12.7);

    /** Equal margins on all sides. */
    public Margins(double allMm) {
      this(allMm, allMm, allMm, allMm);
    }
  }

  /** Standard paper sizes. */
  public enum PageSize {
    LETTER,
    A4,
    LEGAL,
    A3,
    TABLOID
  }

  /** Page orientation. */
  public enum Orientation {
    PORTRAIT,
    LANDSCAPE
  }
}
